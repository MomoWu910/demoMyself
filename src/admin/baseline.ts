/**
 * 理論派彩率基準線。
 *
 * **這些數字不是查來的，是用跟畫面上同一套產生邏輯跑 124.7 萬筆注單算出來的**
 * （`yarn baseline:rtp`，見 admin/rtp-baseline.mjs）。
 *
 * 為什麼要有它：儀表板上的「實際派彩率」單獨看沒有意義。
 * 96% 是正常還是機台配爆了，取決於它該是多少，而「該是多少」同時取決於
 * 賠率表、玩家的下注結構、以及玩法之間的比例——押和局跟押莊的期望值差很遠。
 *
 * 所以基準線一定要跟資料同源。查一個「百家樂 RTP 98.9%」貼上來是最糟的做法：
 * 那是「只押莊」的數字，跟這裡玩家實際的押法不是同一件事。
 *
 * ⚠️ 改了任何一款遊戲的賠率表，或改了種子的下注分布（包括玩家分型與籌碼），
 * 都要重跑 `yarn baseline:rtp`。
 */

