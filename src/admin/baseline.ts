/**
 * 各玩法**單注報酬的標準差**（報酬 = 派彩 ÷ 下注）。
 *
 * ---
 *
 * **這張表是整個告警機制的關鍵，而它一開始並不存在。**
 *
 * 原本的偏離門檻對所有玩法都用同一個係數 2。結果是老虎機在展示樣本下
 * 幾乎永遠亮紅字：它的派彩率會在 72% 到 100% 之間跳，而理論值是 94.21%。
 *
 * 第一個念頭是去調種子參數把數字「弄好看」。那是錯的方向——
 * **數字在跳不是資料的問題，是老虎機本來就抖得比別人厲害**：
 * 三成的局中獎、但有大獎，單注報酬標準差 2.66，是百家樂（1.37）的兩倍。
 * 用同一個門檻看這兩款，不是對老虎機誤報，就是對百家樂漏報。
 *
 * 所以門檻要用每款自己的變異數算，而這個數字跟基準線一樣，
 * **是跑百萬筆量出來的，不是估的**。
 */
export const BASELINE_BET_STD: Record<string, number> = {
    baccarat: 1.37,
    baccaratLive: 1.34,
    roulette: 2.10,
    slot: 2.66,
};

/** 整體。各玩法照種子的比例混合之後的結果 */
export const BASELINE_OVERALL = 0.9724;
export const BASELINE_OVERALL_STD = 2.21;

/** 基準線是用多少筆注單算出來的。展示時要一起講——沒有樣本數的基準線不能信 */
export const BASELINE_SAMPLE = 1_247_104;

/**
 * **有效樣本數**：這批注單相當於幾筆「等額」的注單。
 *
 * `n_eff = (Σ下注額)² ÷ Σ(下注額²)`
 *
 * 為什麼不能直接用筆數：因為派彩率是**按金額加權**的平均，不是按筆數。
 * 一千筆 10 元的注加上一筆 10000 元的注，筆數是 1001，
 * 但那一筆大注一個人就佔了一半的權重——這批資料的可信度接近「兩筆」，不是一千零一筆。
 *
 * 這件事在這個 demo 裡是看得見的：大戶的單注是苦工的兩百倍，
 * 老虎機五千多筆注單的**有效樣本數只有六百上下**。
 * 用筆數當樣本量去算誤差，會把誤差低估三倍，然後報表就開始每天誤報。
 *
 * @param stake   下注額總和
 * @param stakeSq 下注額平方和
 */
export function effectiveSample(stake: number, stakeSq: number): number {
    if (stakeSq <= 0) return 0;
    return (stake * stake) / stakeSq;
}

/**
 * 判斷一個實際派彩率偏離基準線多少，回傳「該不該擔心」。
 *
 * 門檻是**這款玩法自己的標準誤**：`SE = 該玩法的單注報酬標準差 ÷ √有效樣本數`。
 * 兩個輸入都不是拍腦袋來的——標準差跑百萬筆量出來，
 * 有效樣本數由實際的下注金額分布算出來。
 *
 * 這仍然是估計不是統計檢定（真正的檢定要處理報酬分布的厚尾），
 * 目的是把「明顯異常」跟「還在噪音裡」分開，
 * 不是要給出一個可以拿去做決策的 p 值。
 *
 * @param sample 有效樣本數，用 `effectiveSample()` 算
 * @param std    該玩法的單注報酬標準差，取自 `BASELINE_BET_STD`
 */
export function deviationLevel(
    actual: number,
    baseline: number,
    sample: number,
    std = BASELINE_OVERALL_STD,
): 'normal' | 'watch' | 'alert' {
    // 有效樣本數太少的時候不做判斷。**「資料不夠」跟「正常」是兩件事**，
    // 但在告警的語境下它們該有同一個結果：不要吵
    if (sample < 30) return 'normal';
    const se = std / Math.sqrt(sample);
    const z = Math.abs(actual - baseline) / se;
    if (z > 3) return 'alert';
    if (z > 2) return 'watch';
    return 'normal';
}
