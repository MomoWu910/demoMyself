/**
 * 判斷一個實際派彩率偏離基準線多少，回傳「該不該擔心」。
 *
 * 門檻用**相對於樣本數**的粗略標準誤估計，不是固定的百分點：
 * 一百筆注單偏離 10 個百分點是常態，十萬筆偏離 2 個百分點才值得看。
 * 用固定門檻的報表會在資料少的時候一直誤報，然後大家就學會忽略它。
 *
 * 這是估計不是統計檢定——單注的變異數各款差很遠（直注賠 35 倍、莊閒賠 1 倍），
 * 這裡取一個中間值當係數。目的是把「明顯異常」跟「還在噪音裡」分開，
 * 不是要給出一個可以拿去做決策的 p 值。
 */
export function deviationLevel(actual: number, baseline: number, sample: number): 'normal' | 'watch' | 'alert' {
    if (sample < 30) return 'normal';
    // 粗估標準誤：單注報酬的標準差抓 2（混合了低賠率與高賠率注別），除以根號樣本數
    const se = 2 / Math.sqrt(sample);
    const z = Math.abs(actual - baseline) / se;
    if (z > 3) return 'alert';
    if (z > 2) return 'watch';
    return 'normal';
}
